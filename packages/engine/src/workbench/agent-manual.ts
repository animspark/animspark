/**
 * The workspace manual for a coding agent (CLAUDE.md / AGENTS.md).
 *
 * Audience: a general-purpose coding agent (Claude Code, Codex, Cursor, …) editing a film in a
 * local workspace with its own file tools and the `anim` CLI.
 *
 * `anim new` writes it into the workspace root, where the agent reads it on entry. The body comes
 * from prompts/system_prompt.md plus the list of installed skills (see code-prompt.ts); this file
 * only adds the header.
 */
import { renderCodePrompt } from '../scene/workspace/code-prompt';

const INTRO = `<!-- Generated by anim new. Do not edit by hand: running anim new again overwrites it. -->

# AnimSpark film workspace

This directory is an AnimSpark film workspace. The parameters of this job (aspect ratio and stage size, plus the target duration and content language when they were given) are in \`../runtime/task.json\`. Read it before you start; decide anything it leaves out from the user's request.

The \`anim\` CLI on your PATH does the rest: \`anim --help\` lists the commands, \`anim <command> --help\` shows arguments and examples.`;

/** Renders the full manual (CLAUDE.md and AGENTS.md share the same text). */
export function renderAgentManual(): string {
  return `${INTRO}\n\n${renderCodePrompt({ surface: 'local' })}\n`;
}
